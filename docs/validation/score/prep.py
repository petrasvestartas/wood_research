# prep.py <data dir>: the scoreboard's fixed inputs, written once into <data dir>:
#   cases.tsv  suite case family tol specA specB occtA occtB   (1850/5 corpus + 785/5 timber + 70/5 chair cases)
#   ref.tsv    suite case op status faces edges vertices valid volume meshvol meshacc   (OCCT results)
# OCCT results come from occt_ref_full*.tsv (occt_ref.py ref shards: adaptive volumes, current units) where it has them, else
# from the stored bench results. Timber cases whose second operand lacks the move of their OCCT spec (*_rot, *_self) get it.
# The nist_edm__fork cutters and rotation centres were placed when OCCT read that inch file 25.4 times too large: they
# are scaled by 1/25.4 here, otherwise four of the five cases are disjoint.
# Our corpus STEP operands are pinned to the shell stepfix/operands.tsv pairs with OCCT's (step=<path>#<i>), so the
# driver does not mesh every shell to find the largest.
import glob, os, re, sys
D = sys.argv[1]
S = '/tmp/claude-0/-home-user-wood-research/8b288b7c-72c4-56e2-9565-a39939e050f9/scratchpad'
BENCH = '/home/user/session_data/brep_boolean_bench'
CX = '/tmp/claude-0/-home-user/8b288b7c-72c4-56e2-9565-a39939e050f9/scratchpad/stepfix/cx/run/cases.tsv'
STEPFIX = S + '/stepfix/operands.tsv'
CX_OCCT = '/home/user/wood_research/docs/validation/complex_bench/raw/raw_occt.txt'
FAMILY = {'nist_edm': 'NIST', 'occt_data': 'OCCT data', 'occt_booltest': 'OCCT data', 'hf_brepground': 'BRepGround',
          'hf_zero_to_cad': 'Zero-To-CAD', 'mcneel_rebuilt': 'McNeel', 'hf_brepmfr': 'BRepMFR', 'github_misc': 'github',
          'forum': 'forum', 'pair': 'pair', 'elem': 'timber element', 'joint': 'timber joint', 'chair': 'chair', 'twisted': 'chair'}


def family(case):
    return FAMILY[re.match(r'[a-z_]+?(?=__|#|\d|_pose|_rot|_self|$)', case).group(0)]


def absolute(spec):
    return re.sub(r'(?<=step=)(?!/)', BENCH + '/', spec)


shell = {}
for l in open(STEPFIX) if os.path.exists(STEPFIX) else []:
    w = l.rstrip('\n').split('\t')
    if w[0] == 'corpus' and '#' in w[4].split(' ')[0]:
        shell[(w[1], w[2])] = w[4].split(' ')[0]


def pinned(case, side, spec):
    s = absolute(spec)
    if spec.startswith('step=') and (case, side) in shell:
        s = 'step=' + BENCH + '/' + shell[(case, side)] + spec[spec.index('|'):] if '|' in spec else 'step=' + BENCH + '/' + shell[(case, side)]
    return s


def scaled(spec, k):
    # a primitive and the lengths of its moves times k (step= operands keep their own size, only their moves scale)
    out = []
    for i, part in enumerate(spec.split('|')):
        kind, arg = part.split('=', 1)
        v = arg.split(',')
        which = {'t': range(3), 'r': range(4, 7), 'm': (3, 7, 11)}[kind] if i else range(0 if kind == 'step' else len(v))
        out.append(kind + '=' + ','.join('%.12g' % (float(x) * k) if j in which else x for j, x in enumerate(v)))
    return '|'.join(out)


rows, fixed = [], []
for l in open(BENCH + '/results/cases.tsv'):
    w = l.rstrip('\n').split('\t')
    if w[0].startswith('nist_edm__fork#'):
        w[2] = scaled(w[2], 1 / 25.4)
    rows.append(['corpus', w[0], family(w[0]), '1e-7', pinned(w[0], 'A', w[1]), pinned(w[0], 'B', w[2]), absolute(w[1]), absolute(w[2])])
for l in open(CX):
    name, title, tol, a, b, ca, cb = l.rstrip('\n').split('\t')
    ca, cb = ca.replace('$S', S), cb.replace('$S', S)
    if '|m=' not in b and '|m=' in cb:
        b += cb[cb.index('|m='):]
        fixed.append(name)
    rows.append(['cx', name, family(name), tol, a, b, ca, cb])
with open(D + '/cases.tsv', 'w') as f:
    f.write('#suite\tcase\tfamily\ttol\tspecA\tspecB\tocctA\tocctB\n')
    for r in rows:
        f.write('\t'.join(r) + '\n')

ref = {}
for l in open(BENCH + '/results/bool_occt.txt'):
    c, _, rest = l.rstrip('\n').split('\t', 2)
    p = rest.split()
    ok = p[2] == 'ok'
    ref[('corpus', c, p[1])] = [p[2]] + (p[4:8] + [p[10]] if ok else ['0', '0', '0', '0', 'nan'])
for l in open(CX_OCCT):
    p = l.split()
    if p[1] != 'OP' or p[2] in ('xor', 'xor3'):
        continue
    op, ok = p[2].replace('xorcells', 'xor'), p[3] == 'ok'
    ref[('cx', p[0], op)] = [p[3]] + ([p[7], p[8], p[9], p[15], p[21]] if ok else ['0', '0', '0', '0', 'nan'])
for k in ref:
    ref[k] += ['-', '-']
regenerated = 0
for l in (l for f in sorted(glob.glob(D + '/occt_ref_full*.tsv')) for l in open(f)):
    w = l.rstrip('\n').split('\t')
    ref[(w[0], w[1], w[2])] = w[3:11]
    regenerated += 1
with open(D + '/ref.tsv', 'w') as f:
    for k, v in sorted(ref.items()):
        f.write('\t'.join(list(k) + v) + '\n')
print(len(rows), 'cases,', len(ref), 'reference booleans (%d regenerated by occt_ref.py ref), move added to' % regenerated, ' '.join(fixed) or 'none')
